#!/usr/bin/env python3
"""Scene backgrounds for the seven Flow screens, derived from the selected originals by local processing only.

    python3 scripts/flow/prepare_backgrounds.py <design-assets dir> public/flow/bg [--preview dir]

The originals contain generator text, buttons and HUD. Each job crops away the regions that the React interface
replaces (side panels, headers, trays) and reconstructs small covered areas (labels, pins, a card) with OpenCV
inpainting (Telea) from the surrounding pixels. No pixels are generated by a model; every operation is recorded in
provenance.json together with the source hash, so a reviewer can see exactly what was reconstructed. Large
reconstructions are flagged as `approximate`.
"""
import hashlib, json, os, sys
import cv2
import numpy as np

src_dir, out = sys.argv[1], sys.argv[2]
preview = sys.argv[sys.argv.index('--preview') + 1] if '--preview' in sys.argv else None
os.makedirs(out, exist_ok=True)
if preview: os.makedirs(preview, exist_ok=True)

# rects are [x, y, w, h] in the native pixels of the original (1376×768)
JOBS = {
    'inicio': {'src': '01-inicio/E-garaje-refinado.jpg', 'crop': [459, 0, 917, 768], 'inpaint': []},
    'headquarters': {'src': '02-headquarters/A-campus.jpg', 'crop': [0, 100, 1376, 578], 'inpaint': [
        [668, 118, 226, 78],    # "CUARTEL GENERAL" pin
        [243, 240, 128, 72], [262, 300, 26, 18],    # "TALLER" pin and tip
        [1098, 200, 150, 64], [1113, 258, 26, 18],  # "FÁBRICA" pin
        [941, 436, 144, 64], [960, 494, 26, 18],    # "GARAJE" pin
    ]},
    'taller': {'src': '03-taller/A.jpg', 'crop': [104, 94, 1060, 516], 'inpaint': [], 'approximate': True,
        # the reference sedan, removed so the GT-01 layers can stand there: wall extended upward-to-down, floor by row
        'remove': {'poly': [(306, 378), (330, 358), (400, 338), (480, 316), (560, 306), (660, 306), (760, 323), (840, 348), (950, 383), (1040, 408), (1070, 428), (1070, 497), (1002, 514), (998, 544), (878, 544), (868, 514), (542, 514), (538, 544), (406, 544), (402, 507), (318, 497), (304, 462)],
                   'floorRect': [296, 462, 790, 92], 'horizon': 462, 'wall': 'extend'}},
    'fabrica': {'src': '04-fabrica/A.jpg', 'crop': [0, 76, 1376, 556], 'inpaint': [
        [88, 284, 230, 70], [412, 284, 228, 70], [748, 284, 206, 46], [1048, 284, 260, 70],   # station titles and bars
        [110, 584, 156, 34], [428, 584, 190, 34], [764, 584, 186, 34], [1084, 584, 222, 34],  # floor labels
        [640, 632, 96, 24],     # tray tab
    ]},
    'garaje': {'src': '05-garaje/A.jpg', 'crop': [432, 0, 944, 600], 'inpaint': [], 'approximate': True,
        # the reference car, removed so the selected vehicle can stand there: brick tiled from above, platform by row
        'remove': {'poly': [(510, 398), (560, 368), (700, 323), (800, 293), (880, 278), (1000, 280), (1150, 298), (1287, 338), (1308, 380), (1303, 482), (1202, 502), (1192, 534), (1058, 534), (1040, 502), (732, 502), (722, 534), (588, 534), (578, 502), (518, 492), (507, 460)],
                   'floorRect': [500, 466, 815, 84], 'horizon': 466, 'wall': 'periodic', 'period': 44}},
    'cofres': {'src': '06-cofres/B.jpg', 'crop': [0, 0, 1376, 636], 'inpaint': [
        [520, 12, 340, 108],    # title
        [1240, 22, 100, 40], [1335, 5, 30, 30], [12, 5, 30, 30],   # BACK and corner icons
        [394, 112, 176, 276],   # generated reward card (the real card is drawn by React)
    ]},
    'configuracion': {'src': '07-configuracion/A.jpg', 'crop': [0, 0, 1376, 768], 'inpaint': [
        [330, 118, 718, 532],   # generated settings panel (the real panel is drawn by React)
    ], 'approximate': True, 'blur': 9},
}

def remove_object(img, spec):
    """Structure-guided removal of a large object: wall pixels are continued from the clean band above the hole
    (tiled with the masonry period, or extended for plain walls) with a falloff towards the floor; floor pixels are
    interpolated along each row between the clean floor on both sides. Returns the image and the hole mask."""
    H, W = img.shape[:2]
    hole = np.zeros((H, W), np.uint8)
    cv2.fillPoly(hole, [np.array(spec['poly'], np.int32)], 255)
    hole = cv2.dilate(hole, np.ones((9, 9), np.uint8))
    fx, fy, fw, fh = spec['floorRect']
    hole[fy:fy + fh, fx:fx + fw] = 255
    hz = spec['horizon']
    res = img.astype(np.float32).copy()
    for x in range(W):
        col = np.where(hole[:hz, x] > 0)[0]
        if not len(col):
            continue
        top = col.min()
        span = max(1, hz - top)
        for y in col:
            if spec['wall'] == 'periodic':
                P = spec['period']
                sy = top - P + ((y - top) % P)
            else:
                sy = top - 2
            fall = 1 - 0.32 * ((y - top) / span) ** 1.3
            res[y, x] = img[max(0, sy), x].astype(np.float32) * fall
    for y in range(hz, H):
        xs = np.where(hole[y] > 0)[0]
        if not len(xs):
            continue
        x0, x1 = max(0, xs.min() - 1), min(W - 1, xs.max() + 1)
        a, b = img[y, max(0, x0 - 6):x0 + 1].astype(np.float32).mean(0), img[y, x1:x1 + 7].astype(np.float32).mean(0)
        t = (xs - x0) / max(1, x1 - x0)
        res[y, xs] = a[None, :] * (1 - t[:, None]) + b[None, :] * t[:, None]
    # feather the seam: blend a lightly blurred result over the original near the hole border
    soft = cv2.GaussianBlur(hole.astype(np.float32) / 255, (0, 0), 3)
    blurred = cv2.GaussianBlur(res, (0, 0), 1.2)
    out = img.astype(np.float32) * (1 - soft[..., None]) + blurred * soft[..., None]
    return np.clip(out, 0, 255).astype(np.uint8), hole

prov = {'method': 'crop; OpenCV inpaint (Telea, radius 9) on small listed rects; structure-guided removal of the reference cars (wall continued from above, floor interpolated per row); no generative model', 'jobs': {}}
for name, job in JOBS.items():
    path = os.path.join(src_dir, job['src'])
    raw = open(path, 'rb').read()
    img = cv2.imdecode(np.frombuffer(raw, np.uint8), cv2.IMREAD_COLOR)
    H, W = img.shape[:2]
    mask = np.zeros((H, W), np.uint8)
    for x, y, w, h in job['inpaint']:
        mask[y:y + h, x:x + w] = 255
    if job['inpaint']:
        mask = cv2.dilate(mask, np.ones((5, 5), np.uint8))
        img = cv2.inpaint(img, mask, 9, cv2.INPAINT_TELEA)
    if job.get('remove'):
        img, _ = remove_object(img, job['remove'])
    if job.get('blur'):
        img = cv2.GaussianBlur(img, (0, 0), job['blur'])
    x, y, w, h = job['crop']
    res = img[y:y + h, x:x + w]
    cv2.imwrite(os.path.join(out, f'{name}.webp'), res, [cv2.IMWRITE_WEBP_QUALITY, 84])
    if preview:
        dbg = img.copy()
        for rx, ry, rw, rh in job['inpaint']:
            cv2.rectangle(dbg, (rx, ry), (rx + rw, ry + rh), (0, 0, 255), 2)
        cv2.rectangle(dbg, (x, y), (x + w, y + h), (0, 255, 0), 2)
        cv2.imwrite(os.path.join(preview, f'{name}-ops.jpg'), dbg, [cv2.IMWRITE_JPEG_QUALITY, 80])
    prov['jobs'][name] = {
        'source': job['src'], 'sourceSha256': hashlib.sha256(raw).hexdigest(), 'sourceSize': [W, H],
        'crop': job['crop'], 'inpaintRects': job['inpaint'], 'blur': job.get('blur', 0), 'removedObject': job.get('remove'),
        'output': f'{name}.webp', 'outputSize': [w, h], 'bytes': os.path.getsize(os.path.join(out, f'{name}.webp')),
        'quality': 'approximate reconstruction of a large area' if job.get('approximate') else 'small areas reconstructed',
    }
json.dump(prov, open(os.path.join(out, 'provenance.json'), 'w'), indent=1)
print(json.dumps({k: (v['outputSize'], v['bytes'], v['quality']) for k, v in prov['jobs'].items()}, indent=1))
